"""Write a DFlash2 training set: the target model answers a chat dataset again, on Cortex Training.

A draft trains best on the target's own text, so every assistant turn of the source conversations is
regenerated by the target, reasoning included, one user turn at a time: each turn's prompt is the
conversation so far with the earlier turns' new answers.

A conversation is kept only if every turn closes its thinking and gives an answer; one that runs out of
tokens mid-thought on any turn is dropped. The out directory gets ``regenerated.jsonl`` (every kept conversation),
``train.jsonl`` and ``heldout.jsonl``. The sampling settings, the drop rules and the split follow SpecForge's ``regenerate_train_data.py``.
"""

from __future__ import annotations

import hashlib
import json
import logging
import time
from concurrent.futures import ThreadPoolExecutor
from dataclasses import dataclass
from dataclasses import field
from pathlib import Path
from typing import Any

import chz
from recipes.dflash2.task import assistant_turn
from recipes.dflash2.task import iter_jsonl
from recipes.dflash2.task import regeneration_input_error
from recipes.dflash2.task import split_and_dedup
from recipes.utils import build_job
from recipes.utils import make_client
from recipes.utils import running_job

logger = logging.getLogger(__name__)
logging.getLogger("httpx").setLevel(logging.WARN)
logging.getLogger("urllib3").setLevel(logging.WARN)


@chz.chz
class Config:
    # Directory for regenerated.jsonl, train.jsonl and heldout.jsonl.
    out_dir: str
    # Legacy JSON connection file. Omit it to use `connection` or the default profile.
    config: str | None = None
    # Snowflake connection profile name (connections.toml). Use config or connection, not both.
    connection: str | None = None
    job_id: str | None = None  # a running inference endpoint of the target

    # The target. The endpoint is its catalog inference file; job_config= replaces it with a file.
    model: str = "Qwen/Qwen3.5-4B"
    context: str = "standard"
    hardware: str = "h200"
    job_config: str | None = None
    debug_image_tag: str | None = None
    keep_job: bool = False

    # Source conversations: a Hugging Face chat dataset with `messages`, or a JSONL file of
    # `conversations` / `messages` rows. The first num_conversations rows are used.
    dataset: str = "HuggingFaceH4/ultrachat_200k"
    dataset_split: str = "train_sft"
    prompts_path: str | None = None
    num_conversations: int = 16000

    temperature: float = 0.6
    top_p: float = 0.95
    top_k: int = 20
    max_tokens: int = 3072
    seed: int = 0

    # Prompts per generate request, and requests in flight.
    batch_size: int = 512
    concurrency: int = 8

    heldout: int = 300
    dedup_prefix_chars: int = 700


@dataclass
class Regeneration:
    """One conversation being answered again: its user turns, and the messages written so far."""

    id: str
    users: list[str]
    messages: list[dict[str, str]] = field(default_factory=list)
    dropped: str | None = None

    @property
    def done(self) -> bool:
        return self.dropped is not None or sum(m["role"] == "assistant" for m in self.messages) == len(self.users)

    def next_prompt(self) -> list[dict[str, str]]:
        """The conversation so far plus the next user turn; earlier answers go back without their reasoning."""
        turn = sum(m["role"] == "assistant" for m in self.messages)
        history = [{"role": m["role"], "content": m["content"]} for m in self.messages]
        return history + [{"role": "user", "content": self.users[turn]}]


def load_conversations(config: Config) -> list[tuple[str, list[dict[str, Any]]]]:
    """``(id, messages)`` of the first ``num_conversations`` source rows."""
    if config.prompts_path:
        rows = iter_jsonl(config.prompts_path, limit=config.num_conversations)
        return [
            (str(row.get("id", index)), list(row.get("conversations") or row.get("messages") or ()))
            for index, row in enumerate(rows)
        ]
    from datasets import load_dataset

    dataset = load_dataset(config.dataset, split=config.dataset_split)
    dataset = dataset.select(range(min(config.num_conversations, len(dataset))))
    return [
        (str(row.get("prompt_id") or row.get("id") or index), [{"role": m["role"], "content": m["content"]} for m in row["messages"]])
        for index, row in enumerate(dataset)
    ]


def start(conversations: list[tuple[str, list[dict[str, Any]]]]) -> tuple[list[Regeneration], int]:
    """The regenerations to run, and how many source conversations were skipped as unusable."""
    work, skipped = [], 0
    for conversation_id, messages in conversations:
        if regeneration_input_error(messages) is not None:
            skipped += 1
            continue
        system = [{"role": "system", "content": m["content"]} for m in messages if m["role"] == "system"]
        users = [m["content"] for m in messages if m["role"] == "user"]
        work.append(Regeneration(id=conversation_id, users=users, messages=system))
    return work, skipped


def prompt_seed(base: int, conversation_id: str, turn: int) -> int:
    """A per-prompt sampling seed, so a rerun samples every turn the same way."""
    digest = hashlib.sha256(f"{base}:{conversation_id}:{turn}".encode()).hexdigest()
    return int(digest[:8], 16) % (2**31)


def thinking_prompt_ids(tokenizer: Any, messages: list[dict[str, str]]) -> list[int]:
    """Token ids of ``messages`` with the target's template, ending in the opening of a thinking block."""
    ids = tokenizer.apply_chat_template(messages, tokenize=True, add_generation_prompt=True, enable_thinking=True)
    if isinstance(ids, dict) or hasattr(ids, "input_ids"):
        ids = ids["input_ids"]
    return list(ids)


def generate_chunked(
    client: Any, job_id: str, prompts: list[list[int]], params: list[dict[str, Any]], *, batch_size: int, concurrency: int
) -> list[dict[str, Any]]:
    """Generate ``prompts`` in requests of ``batch_size``, ``concurrency`` of them in flight; results in prompt order."""

    def run(start: int) -> list[dict[str, Any]]:
        batch = prompts[start : start + batch_size]
        request_id = client.generate(job_id, prompts=batch, sampling_params=params[start : start + batch_size])
        results = client.poll_request(job_id, request_id).get("results") or []
        if len(results) != len(batch):
            raise RuntimeError(f"asked for {len(batch)} completions, got {len(results)}")
        return results

    with ThreadPoolExecutor(max_workers=max(1, concurrency)) as pool:
        chunks = list(pool.map(run, range(0, len(prompts), batch_size)))
    return [result for chunk in chunks for result in chunk]


def regenerate(client: Any, job_id: str, work: list[Regeneration], tokenizer: Any, config: Config, max_seq_len: int) -> None:
    """Answer every conversation's user turns in order, one turn of all conversations per round."""
    stop = [tokenizer.convert_tokens_to_ids("<|im_end|>")]
    for turn in range(max((len(w.users) for w in work), default=0)):
        active = [w for w in work if not w.done]
        if not active:
            return
        started = time.time()
        prompts = [thinking_prompt_ids(tokenizer, w.next_prompt()) for w in active]
        sendable = []
        for w, prompt in zip(active, prompts):
            if len(prompt) + config.max_tokens > max_seq_len:
                w.dropped = "the conversation outgrows the endpoint's context"
            else:
                sendable.append((w, prompt))
        params = [
            {
                "temperature": config.temperature,
                "top_p": config.top_p,
                "top_k": config.top_k,
                "max_tokens": config.max_tokens,
                "stop_token_ids": stop,
                "seed": prompt_seed(config.seed, w.id, turn),
            }
            for w, _ in sendable
        ]
        results = generate_chunked(
            client, job_id, [p for _, p in sendable], params, batch_size=config.batch_size, concurrency=config.concurrency
        )
        for (w, _), result in zip(sendable, results):
            message, reason = assistant_turn(result.get("text") or "")
            if message is None:
                w.dropped = reason
            else:
                w.messages += [{"role": "user", "content": w.users[turn]}, message]
        kept = sum(1 for w, _ in sendable if not w.dropped)
        logger.info(
            "turn %d: %d prompts, %d answered, %d dropped (%.0fs)", turn + 1, len(active), kept, len(active) - kept, time.time() - started
        )


def main(config: Config) -> dict[str, Any]:
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
    out = Path(config.out_dir).expanduser()
    out.mkdir(parents=True, exist_ok=True)
    work, skipped = start(load_conversations(config))
    logger.info("regenerating %d conversations (%d skipped as unusable)", len(work), skipped)

    body = build_job(
        "inference",
        model=config.model,
        context=config.context,
        hardware=config.hardware,
        job_config=config.job_config,
        debug_image_tag=config.debug_image_tag,
    )
    sampling = next(sub for sub in body["sub_job_configs"] if sub.get("job_type") == "sampling")

    from transformers import AutoTokenizer

    tokenizer = AutoTokenizer.from_pretrained(sampling["model_name"])
    client = make_client(config.config, config.connection)
    with running_job(client, body, job_id=config.job_id, keep_job=config.keep_job or config.job_id is not None) as job_id:
        regenerate(client, job_id, work, tokenizer, config, int(sampling["inference_config"]["max_seq_len"]))

    rows = [{"id": w.id, "conversations": w.messages, "status": "success"} for w in work if w.dropped is None]
    train, held, duplicates = split_and_dedup(rows, heldout=config.heldout, seed=0, prefix_chars=config.dedup_prefix_chars)
    for name, part in (("regenerated", rows), ("train", train), ("heldout", held)):
        with open(out / f"{name}.jsonl", "w", encoding="utf-8") as handle:
            handle.writelines(json.dumps(row, ensure_ascii=False) + "\n" for row in part)
    summary = {
        "source": len(work) + skipped,
        "skipped": skipped,
        "dropped": sum(1 for w in work if w.dropped),
        "kept": len(rows),
        "train": len(train),
        "heldout": len(held),
        "duplicates_dropped": duplicates,
    }
    logger.info("wrote %s: %s", out, summary)
    return summary


if __name__ == "__main__":
    chz.nested_entrypoint(main)
